(
    ID                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CONNECTION_ID               UUID        NOT NULL UNIQUE,
    CONNECTION_NAME             VARCHAR(64) NOT NULL UNIQUE,
